"""Generates src/Forward.h: classes that forward every IDirect3D9 / IDirect3DDevice9 method to the
real object, so the proxy only overrides the methods it cares about.

usage:
  gen_forward.py <path to the Windows SDK shared/d3d9.h> > src/Forward.h
"""
import re
import sys

INTERFACES = (("IDirect3D9", "Direct3D9Forward"), ("IDirect3DDevice9", "Device9Forward"))
METHOD = re.compile(r"STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\)|\((\w+)\))\s*\(THIS_?\s*(.*?)\)\s*PURE;")


def methods(header, interface):
    body = re.search(rf"DECLARE_INTERFACE_\({interface},\s*IUnknown\)\s*\{{(.*?)\n\}};", header, re.S).group(1)
    for m in METHOD.finditer(body):
        ret, name = (m.group(1), m.group(2)) if m.group(2) else ("HRESULT", m.group(3))
        params, names = [], []
        for i, param in enumerate(p.strip() for p in m.group(4).split(",") if p.strip()):
            words = [w for w in re.findall(r"\w+", param) if w != "CONST"]
            if param.endswith("*") or len(words) == 1:  # unnamed in d3d9.h, e.g. "CONST D3DLIGHT9*"
                param += f" arg{i}"
                words.append(f"arg{i}")
            params.append(param)
            names.append(words[-1])
        yield ret, name, ", ".join(params), names


def main():
    header = open(sys.argv[1], encoding="latin-1").read()
    out = ["// Generated by tools/gen_forward.py from the Windows SDK d3d9.h. Do not edit.",
           "#pragma once", "#include <d3d9.h>", ""]
    for interface, cls in INTERFACES:
        out += [f"class {cls} : public {interface} {{", "public:",
                f"  explicit {cls}({interface}* real) : real_(real) {{}}",
                f"  virtual ~{cls}() = default;",
                f"  {interface}* Real() const {{ return real_; }}", ""]
        for ret, name, params, names in methods(header, interface):
            body = f"real_->{name}({', '.join(names)})"
            body = f"{body};" if ret == "void" else f"return {body};"
            out.append(f"  {ret} STDMETHODCALLTYPE {name}({params}) override {{ {body} }}")
        out += ["", "protected:", f"  {interface}* real_;", "};", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
