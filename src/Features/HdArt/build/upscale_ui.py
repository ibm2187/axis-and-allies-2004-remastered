"""Generate a high-resolution UI art set for Axis & Allies (2004) with Real-ESRGAN.

UI textures are referenced as "/UI/%s/Game/...". AA.exe fills %s with the screen width ("%d" of
the global at 0xB396D0) and, when that file does not exist, drops the "%s/" segment and loads the
base art (made for 1024x768, 1 pixel per layout unit). The 800 and 1280 sets are the base art
rescaled by width/1024, tiled borders included. So a "3840" folder is picked up at 3840x2160 with
no executable change; its textures are the base size times screenH/768 (2.8125 at 2160), which
maps them 1:1 to screen pixels with the widescreen layout space.

Sources: the 1280 art where it exists (more detail), else the base art; each nation skin's own
overrides are upscaled into skins/<nation>/. RGB and alpha go through realesrgan-x4plus
separately (transparent pixels are first filled with nearby colours so edges don't darken), then
Lanczos to the target size. 4x results are cached by source hash.

usage: upscale_ui.py <game dir> --esrgan <realesrgan-ncnn-vulkan.exe> [--width 3840 --height 2160]
                     [--cache DIR] [--clean]
Writes loose files under <game dir>/data and <game dir>/skins/<nation>, listed in
data/upscale-generated.txt (removed again on the next run, or alone with --clean).
"""
import argparse
import hashlib
import io
import pathlib
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import zlib

import numpy as np
from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "Shared"))
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from rwd import Rwd  # noqa: E402

NATIONS = ["USA", "GBR", "GER", "RUS", "JPN"]
REF = re.compile(r"([A-Za-z0-9_ ./\\-]*/%s/[A-Za-z0-9_ ./\\-]+\.(?:tga|png))", re.I)
SKIP_PREFIXES = ("fonts/",)  # glyph sheets are generated by the engine per size
# loaded by fixed paths (e.g. action_button_icon = TechIcons/x.png, unit .tgi recruit icons)
INPLACE = ("properties/techicons/", "properties/propertyicons/", "properties/abilityicons/",
           "properties/denizenicons/", "ui/game/regimentbuttons/", "ui/game/buildingbuttons/",
           "game/messagetypeicons/",
           # pictures and icons drawn in UI boxes or as unit/minimap markers
           "campaign/", "generals/", "metagame/divisions/", "metagame/ui/", "minimap/icons/",
           "nations/", "organizations/", "ui/default/", "ui/game/")
INPLACE_SKIP = re.compile(r"/(800|1024|1280)/|^ui/test/", re.I)
# Textures the game uses at their exact pixel size. Larger command-grid frames gave sheared white
# garbage over every button (seen with the original icons inside, so the frames alone do it);
# larger minimap icons were drawn into the minimap pixel for pixel, big and white. Unit banners
# combine an icon and a nation badge into one image, likely the same way. These keep the shipped art.
FIXED_SIZE = re.compile(r"^(ui/game/sharedtextures/(button(un)?focused|buttonpressed|actionbuttonbordertargeted)\."
                        r"|minimap/|organizations/|nations/[^/]+/[^/]*badge)", re.I)


def set_paths(data):
    """Base paths ("UI/Game/x.tga") of every texture the engine looks up through a /%s/ folder."""
    out = {}
    for n in data.names():
        if not n.lower().endswith((".tgi", ".lst")):
            continue
        for m in REF.finditer(data.read(n).decode("latin-1")):
            p = m.group(1).strip().replace("\\", "/").lstrip("/")
            head, tail = p.split("/%s/", 1)
            if head.lower().startswith(SKIP_PREFIXES):
                continue
            out[f"{head}/{tail}".lower()] = (head, tail)
    # art that only exists in the resolution folders (referenced through code-built names)
    for n in data.names():
        m = re.match(r"^(.*?)/(800|1280)/(.+\.(?:tga|png))$", n, re.I)
        if m and not m.group(1).lower().startswith(SKIP_PREFIXES):
            out.setdefault(f"{m.group(1)}/{m.group(3)}".lower(), (m.group(1), m.group(3)))
    return out


FIXED_REF = re.compile(r"([A-Za-z0-9_ ./\\-]+\.(?:tga|png))", re.I)


def fixed_paths(data):
    """Paths (lower case) of textures some .tgi/.lst references directly, without a /%s/ folder."""
    out = set()
    for n in data.names():
        if n.lower().endswith((".tgi", ".lst")):
            for m in FIXED_REF.finditer(data.read(n).decode("latin-1")):
                p = m.group(1).strip().replace("\\", "/").lstrip("/").lower()
                if "%s" not in p:
                    out.add(p)
    return out


def is_icon(path):
    return path.startswith("properties/") or path.rsplit("/", 1)[-1].startswith("icon")


def pow2(n):
    return 1 << (n - 1).bit_length()


def load(blob):
    im = Image.open(io.BytesIO(blob))
    im.load()
    return im.convert("RGBA")


def fill_transparent(rgba):
    """RGB of fully transparent pixels -> average colour of nearby opaque pixels."""
    a = rgba[..., 3:4].astype(np.float32) / 255
    rgb = rgba[..., :3].astype(np.float32)
    if a.min() > 0:
        return rgba[..., :3]
    out = rgb.copy()
    hole = a[..., 0] == 0
    acc, w = rgb * a, a.copy()
    for _ in range(64):
        if not hole.any():
            break
        acc = (sum(np.roll(acc, s, axis=ax) for ax in (0, 1) for s in (-1, 1)) + acc) / 5
        w = (sum(np.roll(w, s, axis=ax) for ax in (0, 1) for s in (-1, 1)) + w) / 5
        ok = hole & (w[..., 0] > 0)
        out[ok] = acc[ok] / w[ok]
        hole &= ~ok
    return np.clip(out, 0, 255).astype(np.uint8)


def write_tga(im, path):
    """32-bit uncompressed, bottom-left origin, 8 alpha bits (as the game's own files)."""
    w, h = im.size
    px = np.asarray(im.convert("RGBA"))[::-1, :, [2, 1, 0, 3]]
    path.write_bytes(struct.pack("<BBBHHBHHHHBB", 0, 0, 2, 0, 0, 0, 0, 0, w, h, 32, 8) + px.tobytes())


def write_png(im, path):
    """RGBA PNG with the whole image in ONE IDAT chunk. The game's PNG loader reads only the
    first IDAT (all shipped PNGs have one); Pillow splits large images into several, which
    rendered as garbage below the first chunk."""
    w, h = im.size
    px = np.asarray(im.convert("RGBA"))
    raw = np.concatenate([np.zeros((h, 1), np.uint8), px.reshape(h, w * 4)], axis=1).tobytes()  # filter 0

    def chunk(t, body):
        return struct.pack(">I", len(body)) + t + body + struct.pack(">I", zlib.crc32(t + body))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def keep_binary_alpha(im, src):
    """Alpha back to 0/255 when the source art's alpha is only 0/255. The game draws any alpha
    above 0 fully opaque, so the soft edge the upscale and resize give such art showed the colour
    padding of transparent pixels as solid noise (along the top of the HUD panels)."""
    if np.isin(np.asarray(src.getchannel("A")), (0, 255)).all():
        im.putalpha(im.getchannel("A").point(lambda v: 255 if v >= 128 else 0))
    return im


PANEL_BOX = re.compile(r"\s*([LTRB])\s*=\s*\+?([0-9.]+)\s*$")
PANEL_TILE = re.compile(r"texture\s*=\s*/UI/%s/Game/ControlPanel/(\w+)\.tga", re.I)


def panel_tiles(data):
    """{tile name: (L, T, W, H)} of the control panel buttons, in panel units (1024 x 256), that sit
    on its unstretched ends (the widescreen layout keeps them where the shipped art put them)."""
    tiles, box = {}, {}
    for line in data.read("UI/Game/control_panel.tgi").decode("latin-1").splitlines():
        m = PANEL_BOX.match(line)
        if m:
            box[m.group(1)] = float(m.group(2))
        t = PANEL_TILE.search(line)
        if t and t.group(1) != "Background" and len(box) == 4 and box["R"] >= 4 and box["B"] >= 4:
            left, right = box["L"], box["L"] + box["R"]
            if right <= 320 or left >= 792:
                tiles[t.group(1)] = (box["L"], box["T"], box["R"], box["B"])
    return tiles


def trim_panel_tiles(tiles, folder_dir, background):
    """Clear dark opaque pixels of button tiles where the panel itself is transparent. Two shipped
    tiles carry a dark corner past the panel's edge: the British chat button (a black notch above
    the minimap) and the Soviet objectives tab."""
    bg = np.asarray(Image.open(background).convert("RGBA"))[..., 3]
    kx, ky = bg.shape[1] / 1024, bg.shape[0] / 256
    trimmed = []
    for name, (left, top, w, h) in tiles.items():
        path = folder_dir / f"{name}.tga"
        if not path.exists():
            continue
        tile = np.asarray(Image.open(path).convert("RGBA")).copy()
        under = bg[round(top * ky):round((top + h) * ky), round(left * kx):round((left + w) * kx)]
        under = np.asarray(Image.fromarray(under).resize((tile.shape[1], tile.shape[0]), Image.NEAREST))
        stray = (tile[..., 3] > 0) & (under == 0) & (tile[..., :3].max(-1) < 48)
        if stray.any():
            tile[stray, 3] = 0
            write_tga(Image.fromarray(tile), path)
            trimmed.append(f"{path.parents[4].name}/{name}: {int(stray.sum())} px")
    return trimmed


def save(im, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.suffix.lower() == ".tga":
        write_tga(im, path)
    else:
        write_png(im, path)


def upscale_all(jobs, esrgan, cache):
    """jobs: {sha: RGBA image}. Returns {sha: 4x RGBA image}, using and filling the cache."""
    cache.mkdir(parents=True, exist_ok=True)
    todo = {s: im for s, im in jobs.items() if not (cache / f"{s}.png").exists()}
    if todo:
        with tempfile.TemporaryDirectory() as tmp:
            src, dst = pathlib.Path(tmp, "in"), pathlib.Path(tmp, "out")
            src.mkdir(), dst.mkdir()
            for s, im in todo.items():
                px = np.asarray(im)
                Image.fromarray(fill_transparent(px)).save(src / f"{s}_c.png")
                if px[..., 3].min() < 255:
                    Image.fromarray(px[..., 3]).convert("RGB").save(src / f"{s}_a.png")
            print(f"  Real-ESRGAN x4 on {len(list(src.iterdir()))} images ...", flush=True)
            r = subprocess.run([str(esrgan), "-i", str(src), "-o", str(dst), "-n", "realesrgan-x4plus", "-t", "256", "-f", "png"],
                               cwd=pathlib.Path(esrgan).parent, capture_output=True, text=True)
            missing = [s for s in todo if not (dst / f"{s}_c.png").exists()]
            if r.returncode or missing:
                raise SystemExit(f"realesrgan failed ({len(missing)} outputs missing):\n{r.stderr[-2000:]}")
            for s, im in todo.items():
                c = Image.open(dst / f"{s}_c.png").convert("RGB")
                if (dst / f"{s}_a.png").exists():
                    a = Image.open(dst / f"{s}_a.png").convert("L")
                else:
                    a = Image.new("L", c.size, 255)
                c.putalpha(a)
                c.save(cache / f"{s}.png")
    return {s: Image.open(cache / f"{s}.png").convert("RGBA") for s in jobs}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("game_dir")
    ap.add_argument("--esrgan")
    ap.add_argument("--width", type=int, default=3840)
    ap.add_argument("--height", type=int, default=2160)
    ap.add_argument("--cache", default=str(pathlib.Path(__file__).resolve().parents[4] / ".cache" / "upscale"))
    ap.add_argument("--clean", action="store_true", help="only remove previously generated files")
    ap.add_argument("--out", help="write under this folder instead of the game folder (HD pack staging)")
    ap.add_argument("--no-inplace", action="store_true", help="skip the fixed-path icons")
    ap.add_argument("--cursor-scale", type=int, help="mouse cursor size factor (default: screen height / 1080)")
    a = ap.parse_args()
    game = pathlib.Path(a.game_dir)
    root = pathlib.Path(a.out) if a.out else game
    manifest = root / "data" / "upscale-generated.txt"
    if manifest.exists():
        for rel in manifest.read_text(encoding="utf-8").splitlines():
            (root / rel).unlink(missing_ok=True)
        manifest.unlink()
    if a.clean:
        print("removed generated high-resolution UI art")
        return
    if not a.esrgan:
        raise SystemExit("--esrgan is required")

    scale = a.height / 768
    folder = str(a.width)
    data = Rwd(game / "Data.rwd")
    paths = set_paths(data)
    archives = [("data", data, root / "data")] + [
        (n, Rwd(game / "skins" / f"{n}.rwd"), root / "skins" / n) for n in NATIONS if (game / "skins" / f"{n}.rwd").exists()]

    # plan: (output path, source image, target size)
    plan = []
    for key, (head, tail) in sorted(paths.items()):
        if FIXED_SIZE.match(key):
            continue
        base_dims = None
        for name, arc, out in archives:
            b, hi = f"{head}/{tail}", f"{head}/1280/{tail}"
            has_b, has_hi = arc.has(b), arc.has(hi)
            if name != "data" and not (has_b or has_hi):
                continue  # skin doesn't override this texture
            if not (has_b or has_hi):
                break  # no source art at all
            # target size comes from the base art (the skin's own, else the game's)
            ref = arc if has_b else data
            if ref.has(b):
                w, h = load(ref.read(b)).size
            else:
                w, h = load(arc.read(hi)).size
                w, h = w / 1.25, h / 1.25
            if name == "data":
                base_dims = (w, h)
            src = load(arc.read(hi if has_hi else b))
            # the engine stretches every texture to power-of-two sizes on load ("is being
            # resized" in the log); doing it here with Lanczos avoids a second, cruder resample
            size = tuple(pow2(max(1, round(v * scale))) for v in (w, h))
            plan.append((out / head / folder / tail, src, size))
    n_set = len(plan)
    # icons the game loads by a fixed path (no %s): replaced in place, so they are high resolution
    # at every screen size. Only groups drawn into fixed-size UI boxes.
    if not a.no_inplace:
        fixed = fixed_paths(data)
        for name, arc, out in archives:
            for n in arc.names():
                low = n.lower()
                if not (low.startswith(INPLACE) and low.endswith((".png", ".tga"))) or INPLACE_SKIP.search(low):
                    continue
                # resolution-set art is already in the <width> folder, unless some file also loads
                # it by its fixed path (IconPropertySand.png has 800/1280 versions, but the terrain
                # properties load /Properties/PropertyIcons/IconPropertySand.png)
                if (low in paths and not (low in fixed and is_icon(low))) or FIXED_SIZE.match(low):
                    continue
                parts = n.split("/")
                hi = f"{parts[0]}/1280/{'/'.join(parts[1:])}"  # e.g. Properties/1280/TechIcons/x.png
                src = load(arc.read(hi if arc.has(hi) else n))
                w, h = load(arc.read(n)).size
                plan.append((out / n, src, tuple(pow2(max(1, round(v * scale))) for v in (w, h))))
    n_icons = len(plan) - n_set
    # mouse cursor: 32x32 frames with pixel hotspots (Cursors/*.tgi); scaled with the screen
    cursor_scale = max(1, round(a.height / 1080)) if a.cursor_scale is None else a.cursor_scale
    if cursor_scale > 1:
        for n in data.names():
            if n.lower().startswith("cursors/") and n.lower().endswith(".tga"):
                src = load(data.read(n))
                plan.append((root / "data" / n, src, (src.size[0] * cursor_scale, src.size[1] * cursor_scale)))
    print(f"{n_set} textures for the {folder} set (x{scale:.4g} of the base art), {n_icons} icons in place, "
          f"{len(plan) - n_set - n_icons} cursor frames x{cursor_scale}")

    jobs = {}
    for _, src, _ in plan:
        jobs.setdefault(hashlib.sha1(src.tobytes() + str(src.size).encode()).hexdigest(), src)
    big = upscale_all({s: im for s, im in jobs.items() if min(im.size) >= 4}, pathlib.Path(a.esrgan), pathlib.Path(a.cache))

    written = []
    for out, src, size in plan:
        s = hashlib.sha1(src.tobytes() + str(src.size).encode()).hexdigest()
        im = big[s].resize(size, Image.LANCZOS) if s in big else src.resize(size, Image.LANCZOS)
        save(keep_binary_alpha(im, src), out)
        written.append(out)
    tiles = panel_tiles(data)
    default_bg = root / "data" / "UI" / folder / "Game" / "ControlPanel" / "Background.tga"
    for _, _, out in archives:
        panel_dir = out / "UI" / folder / "Game" / "ControlPanel"
        background = panel_dir / "Background.tga" if (panel_dir / "Background.tga").exists() else default_bg
        if panel_dir.exists() and background.exists():
            for line in trim_panel_tiles(tiles, panel_dir, background):
                print(f"  trimmed {line}")
    if cursor_scale > 1:
        for n in ("Cursors/cursors_aa.tgi",):  # cursors.tgi is the engine's commented-out list
            text = data.read(n).decode("latin-1")
            text = re.sub(r"(hotspot_offset\s*=\s*)(\d+)\s*,\s*(\d+)",
                          lambda m: f"{m.group(1)}{int(m.group(2)) * cursor_scale}, {int(m.group(3)) * cursor_scale}", text)
            out = root / "data" / n
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(text.encode("latin-1"))
            written.append(out)
    for _, arc, _ in archives:
        arc.close()
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text("\n".join(str(p.relative_to(root)) for p in written) + "\n", encoding="utf-8")
    print(f"wrote {len(written)} files")


if __name__ == "__main__":
    main()
